//! TypeScript mirror generation (Phase 5c, D23).
//!
//! This is an integration test that is always `#[ignore]`d: it writes files, so
//! `cargo test --workspace` never runs it. `./scripts/gen_types.sh` runs it once
//! with `--ignored --features ts-export`.
//!
//! The whole file is gated on `ts-export` so a plain `cargo clippy
//! --all-targets` or `cargo test --workspace` (which do not enable the feature)
//! never tries to link `ts_rs`.
//!
//! It emits a single module, `src/types/generated/talon_core.ts`, holding the
//! ts-rs declarations of the schema and config types plus the parsed
//! `SCENARIO_DEFAULTS` literal. Every type carries
//! `#[cfg_attr(feature = "ts-export", derive(ts_rs::TS))]`, so the mirror is
//! regenerated from the Rust types that are the schema source of truth (D23).
//!
//! Two aliases are deliberately not emitted: `Arr3` and `PhaseEvent` are Rust
//! type aliases and cannot carry a derive, so their fields inline as
//! `[number, number, number]` and `[number, FlightPhase]`. The hand-written
//! facades define the named aliases in a later commit.
#![cfg(feature = "ts-export")]

use std::path::PathBuf;

use ts_rs::{Config, TS};

use talon_core::avoidance::AvoidanceConfig;
use talon_core::constants::Limits;
use talon_core::faults::{FaultKind, FaultSpec};
use talon_core::scenario::ScenarioConfig;
use talon_core::sim::DivergenceMode;
use talon_core::types::{
    EventLogEntry, FlightData, FlightMeta, FlightPhase, Obstacle, RunSummary, Waypoint,
};

/// The generated banner; `src/types/generated.test.ts` asserts this exact line.
const BANNER: &str = "// GENERATED FILE. DO NOT EDIT. Run ./scripts/gen_types.sh.";

/// ts-rs config for this export.
///
/// `large_int_type = "number"` makes any `u64` that reaches `TS::name` (such
/// as `ScenarioConfig.seed`, unwrapped from its `Option<_>` by `optional`)
/// emit `number` instead of `bigint`. The only bigint surface in the app is the
/// wasm getters in `engine.ts`, which are hand-written and unrelated to these
/// JSON schema types.
fn config() -> Config {
    Config::new().with_large_int("number")
}

/// Emit `export <decl>` for a type. `TS::decl` omits the `export ` keyword.
fn exported<T: TS>() -> String {
    format!("export {}", T::decl(&config()))
}

/// Declaration order. TypeScript hoists type declarations, so a type may
/// reference a later one; the order is chosen for stable diffs, not for
/// dependency resolution.
fn declarations() -> Vec<String> {
    vec![
        exported::<FlightPhase>(),
        exported::<Waypoint>(),
        exported::<Obstacle>(),
        exported::<FlightMeta>(),
        exported::<EventLogEntry>(),
        exported::<FlightData>(),
        exported::<RunSummary>(),
        exported::<AvoidanceConfig>(),
        // The authored fault model: the kind tag, the divergence modes the
        // fault can carry, the tagged fault union, then the config that
        // references it. TypeScript hoists, so order is for stable diffs.
        exported::<FaultKind>(),
        exported::<DivergenceMode>(),
        exported::<FaultSpec>(),
        exported::<ScenarioConfig>(),
        // The input-validation caps, mirroring the Rust constants the core
        // rejects on, so the editor validator reads the same numbers.
        exported::<Limits>(),
    ]
}

/// The full module body: banner, the type declarations, then the defaults
/// literal.
fn module() -> String {
    let mut out = String::new();
    out.push_str(BANNER);
    out.push_str("\n//\n");
    out.push_str("// TypeScript mirrors of the talon-core schema 1.1 types and the scenario\n");
    out.push_str("// config, generated by ts-rs from the Rust source of truth (D23). These\n");
    out.push_str("// replace hand-maintained copies; the Rust fields are authoritative.\n\n");
    out.push_str(&declarations().join("\n\n"));
    out.push_str("\n\n");

    // The default scenario as a literal. Every ScenarioConfig field except the
    // required `id` is `ts(optional)` (each carries a serde default), so
    // listing them all is valid against the generated type. The explicit
    // `: ScenarioConfig` annotation supplies the contextual type, so no
    // `as const` is needed (it would fight the annotation by narrowing each
    // field to a readonly literal type).
    let defaults = ScenarioConfig::default();
    out.push_str(&format!(
        "export const SCENARIO_DEFAULTS: ScenarioConfig = {};\n",
        serde_json::to_string_pretty(&defaults).expect("ScenarioConfig serializes")
    ));

    // The validation caps as a literal, annotated with its type so the
    // editor's validator can read one generated value instead of a
    // hand-copied list of numbers that drifts from the Rust constants.
    out.push_str(&format!(
        "export const LIMITS: Limits = {};\n",
        serde_json::to_string_pretty(&Limits::current()).expect("Limits serializes")
    ));
    out
}

/// Write `src/types/generated/talon_core.ts`, creating the directory if needed.
///
/// Ignored so a plain `cargo test --workspace` never touches the working tree.
#[test]
#[ignore = "writes files; run ./scripts/gen_types.sh, not cargo test"]
fn generate_the_typescript_mirrors() {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out_path = manifest
        .join("..")
        .join("src")
        .join("types")
        .join("generated")
        .join("talon_core.ts");

    let parent = out_path
        .parent()
        .expect("generated path has a parent directory");
    std::fs::create_dir_all(parent).expect("create src/types/generated");

    let body = module();
    std::fs::write(&out_path, &body).expect("write talon_core.ts");

    // The emitted file must carry every schema type and the defaults literal,
    // and `AvoidanceConfig` (nested in the defaults) must serialize to an
    // object so the emitted `SCENARIO_DEFAULTS.avoidance` block is well-formed.
    assert!(body.contains("FlightPhase"));
    assert!(body.contains("FlightData"));
    assert!(body.contains("ScenarioConfig"));
    assert!(body.contains("SCENARIO_DEFAULTS"));
    // The input-validation caps: the `Limits` declaration and the `LIMITS`
    // literal the editor validator reads.
    assert!(body.contains("Limits"));
    assert!(body.contains("LIMITS"));
    let avoid = serde_json::to_value(AvoidanceConfig::default()).expect("serializes");
    assert!(avoid.is_object());

    eprintln!("wrote {}", out_path.display());
}
